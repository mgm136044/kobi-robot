"""Re-point the mesh paths of a converter-made Kobi-20 URDF to the repository layout (kobi20/).

The URDF converter of the 20-joint model writes `assets/<name>.stl` (full) or `assets_light/<name>.stl` (light) next to the URDF.
In this repository the full URDF shares the STL files of the MuJoCo model instead of keeping a second 34 MB copy:

    kobi20/mujoco/meshes/<name>.stl      used by kobi20/mujoco/*.xml and by kobi20/urdf/kobi20_v8.urdf (../mujoco/meshes/)
    kobi20/urdf/assets_light/<name>.stl  decimated meshes used only by kobi20/urdf/kobi20_v8_light.urdf

Only two things change: every `filename="assets/..."` of the full URDF becomes `filename="../mujoco/meshes/..."`, and the first comment
line (which named a script and a folder that are not in this repository) is replaced by a description of the new layout.
Everything else (links, joints, masses, inertias, collision shapes) is copied character for character.

    python3 -I -B tools/kobi20/relocate_urdf.py --variant full  SRC.urdf kobi20/urdf/kobi20_v8.urdf
    python3 -I -B tools/kobi20/relocate_urdf.py --variant light SRC.urdf kobi20/urdf/kobi20_v8_light.urdf

The check that the result still equals the MuJoCo model is tools/kobi20/verify_urdf.py.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

FULL_OLD_PREFIX = 'filename="assets/'
FULL_NEW_PREFIX = 'filename="../mujoco/meshes/'
LIGHT_PREFIX = 'filename="assets_light/'
HEADER_PATTERN = re.compile(r"<!-- generated by [^\n]*? \(Kobi 20-joint edition v8, variant: (full|light)\); do not edit by hand\.")
HEADER_TEMPLATE = (
    "<!-- generated from kobi20/mujoco/kobi20_v8.xml by the Kobi 20-joint URDF converter "
    "(Kobi 20-joint edition v8, variant: {variant}); mesh files: {meshes}; do not edit by hand."
)
MESHES_TEXT = {
    "full": "../mujoco/meshes/ (shared with the MuJoCo model)",
    "light": "assets_light/ (decimated copies, for viewing only)",
}


def relocate(text: str, variant: str) -> str:
    """Return the URDF text with the mesh folder and the first comment line adapted to this repository."""
    if variant == "full":
        if FULL_OLD_PREFIX not in text or LIGHT_PREFIX in text:
            raise ValueError("source is not a full-variant URDF (expected only assets/ mesh paths)")
        text = text.replace(FULL_OLD_PREFIX, FULL_NEW_PREFIX)
    elif LIGHT_PREFIX not in text or FULL_OLD_PREFIX in text:
        raise ValueError("source is not a light-variant URDF (expected only assets_light/ mesh paths)")
    text, count = HEADER_PATTERN.subn(HEADER_TEMPLATE.format(variant=variant, meshes=MESHES_TEXT[variant]), text, count=1)
    if count != 1:
        raise ValueError("the expected first comment line was not found")
    return text


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    parser.add_argument("--variant", choices=("full", "light"), required=True)
    args = parser.parse_args(argv)
    if args.destination.exists():
        print(f"{args.destination} exists; refusing to overwrite", file=sys.stderr)
        return 1
    args.destination.write_text(relocate(args.source.read_text(encoding="utf-8"), args.variant), encoding="utf-8")
    print(f"wrote {args.destination.name} ({args.variant})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
